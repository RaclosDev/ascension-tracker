-- Meals, food logs, recipes and saved foods.

CREATE TABLE meals (
    carbs_pct double precision,
    fat_pct double precision,
    fixed_carbs double precision,
    fixed_fat double precision,
    fixed_protein double precision,
    is_default boolean,
    protein_pct double precision,
    sort_order integer NOT NULL,
    end_time character varying(5),
    start_time character varying(5),
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    icon character varying(255) NOT NULL,
    name character varying(255) NOT NULL,
    user_email character varying(255),
    meal_key character varying(36) DEFAULT (gen_random_uuid())::text,
    CONSTRAINT meals_pkey PRIMARY KEY (id),
    CONSTRAINT uq_meals_user_email_name UNIQUE (user_email, name),
    CONSTRAINT fk_meals_user_email FOREIGN KEY (user_email) REFERENCES users(email) ON UPDATE CASCADE
);
CREATE INDEX idx_meals_user_email ON meals USING btree (user_email);
CREATE UNIQUE INDEX uq_meals_user_key ON meals USING btree (user_email, meal_key);
ALTER TABLE meals ENABLE ROW LEVEL SECURITY;

CREATE TABLE food_logs (
    carbs double precision NOT NULL,
    fat double precision NOT NULL,
    kcal double precision NOT NULL,
    log_date date NOT NULL,
    meal_index integer NOT NULL,
    protein double precision NOT NULL,
    quantity double precision NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    product character varying(255) NOT NULL,
    user_email character varying(255) NOT NULL,
    portions_json jsonb,
    meal_key character varying(36),
    meal_name character varying(100),
    meal_icon character varying(50),
    CONSTRAINT chk_food_logs_non_negative CHECK (((quantity >= (0)::double precision) AND (kcal >= (0)::double precision) AND (protein >= (0)::double precision) AND (carbs >= (0)::double precision) AND (fat >= (0)::double precision))),
    CONSTRAINT food_logs_pkey PRIMARY KEY (id),
    CONSTRAINT fk_food_logs_user_email FOREIGN KEY (user_email) REFERENCES users(email) ON UPDATE CASCADE
);
CREATE INDEX idx_food_logs_email_date ON food_logs USING btree (user_email, log_date);
CREATE INDEX idx_food_logs_log_date ON food_logs USING btree (log_date);
CREATE INDEX idx_food_logs_user_email ON food_logs USING btree (user_email);
ALTER TABLE food_logs ENABLE ROW LEVEL SECURITY;

CREATE TABLE recipes (
    total_carbs double precision NOT NULL,
    total_fat double precision NOT NULL,
    total_kcal double precision NOT NULL,
    total_protein double precision NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    description text,
    name character varying(255) NOT NULL,
    user_email character varying(255) NOT NULL,
    CONSTRAINT recipes_pkey PRIMARY KEY (id),
    CONSTRAINT fk_recipes_user_email FOREIGN KEY (user_email) REFERENCES users(email) ON UPDATE CASCADE
);
CREATE INDEX idx_recipes_user_email ON recipes USING btree (user_email);
ALTER TABLE recipes ENABLE ROW LEVEL SECURITY;

CREATE TABLE saved_foods (
    carbs_per100g double precision NOT NULL,
    fat_per100g double precision NOT NULL,
    kcal_per100g double precision NOT NULL,
    protein_per100g double precision NOT NULL,
    serving_size double precision,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    last_used_at timestamp(6) without time zone,
    brand character varying(255),
    name character varying(255) NOT NULL,
    serving_label character varying(255),
    user_email character varying(255) NOT NULL,
    CONSTRAINT saved_foods_pkey PRIMARY KEY (id),
    CONSTRAINT fk_saved_foods_user_email FOREIGN KEY (user_email) REFERENCES users(email) ON UPDATE CASCADE
);
CREATE INDEX idx_saved_foods_user_email ON saved_foods USING btree (user_email);
CREATE INDEX idx_saved_foods_user_name ON saved_foods USING btree (user_email, name);
ALTER TABLE saved_foods ENABLE ROW LEVEL SECURITY;

-- Users, their settings, consents and login sessions.

-- The application reaches PostgreSQL through its own server-side connection.
-- On Supabase, keep the Data API roles away from every table, existing or created later.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon;
        REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon;
        ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM anon;
        ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON ALL TABLES IN SCHEMA public FROM authenticated;
        REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM authenticated;
        ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM authenticated;
        ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM authenticated;
    END IF;
END
$$;

CREATE TABLE users (
    email character varying(255) NOT NULL,
    name character varying(255),
    picture text,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    google_sub character varying(255),
    tokens_valid_after timestamp with time zone DEFAULT now(),
    id uuid DEFAULT gen_random_uuid() NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (email),
    CONSTRAINT uq_users_id UNIQUE (id),
    CONSTRAINT users_google_sub_key UNIQUE (google_sub)
);
CREATE UNIQUE INDEX idx_users_lower_email ON users USING btree (lower((email)::text));
ALTER TABLE users ENABLE ROW LEVEL SECURITY;

CREATE TABLE user_settings (
    custom_carbs_grams double precision,
    custom_carbs_pct double precision,
    custom_fat_grams double precision,
    custom_fat_pct double precision,
    custom_protein_grams double precision,
    custom_protein_pct double precision,
    goal_weight double precision NOT NULL,
    kcal integer NOT NULL,
    start_date date NOT NULL,
    start_weight double precision NOT NULL,
    weekly_goal double precision NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    updated_at timestamp(6) without time zone,
    macro_strategy character varying(20),
    user_email character varying(255) NOT NULL,
    workout_data jsonb,
    activity_factor double precision,
    age integer,
    height_cm integer,
    sex character varying(1),
    version bigint DEFAULT 0 NOT NULL,
    CONSTRAINT user_settings_pkey PRIMARY KEY (id),
    CONSTRAINT user_settings_user_email_key UNIQUE (user_email),
    CONSTRAINT fk_user_settings_user_email FOREIGN KEY (user_email) REFERENCES users(email) ON UPDATE CASCADE
);
ALTER TABLE user_settings ENABLE ROW LEVEL SECURITY;

CREATE TABLE user_consents (
    id uuid DEFAULT gen_random_uuid() NOT NULL,
    user_id uuid NOT NULL,
    kind character varying(32) NOT NULL,
    version character varying(32) NOT NULL,
    granted boolean NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT user_consents_kind_check CHECK (kind IN ('TERMS', 'PRIVACY', 'HEALTH_DATA', 'AI_HEALTH', 'COACH_TERMS')),
    CONSTRAINT user_consents_pkey PRIMARY KEY (id),
    CONSTRAINT user_consents_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX idx_user_consents_user ON user_consents USING btree (user_id, kind, created_at DESC);
ALTER TABLE user_consents ENABLE ROW LEVEL SECURITY;

CREATE TABLE refresh_tokens (
    expiry_date timestamp(6) with time zone NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    email character varying(255) NOT NULL,
    token character varying(255) NOT NULL,
    replaced_at timestamp(6) with time zone,
    family_id character varying(64) NOT NULL,
    grace_used boolean DEFAULT false NOT NULL,
    CONSTRAINT refresh_tokens_pkey PRIMARY KEY (id),
    CONSTRAINT refresh_tokens_token_key UNIQUE (token),
    CONSTRAINT fk_refresh_tokens_email FOREIGN KEY (email) REFERENCES users(email) ON UPDATE CASCADE
);
CREATE INDEX idx_refresh_tokens_email ON refresh_tokens USING btree (email);
CREATE INDEX idx_refresh_tokens_expiry_date ON refresh_tokens USING btree (expiry_date);
CREATE INDEX idx_refresh_tokens_family_id ON refresh_tokens USING btree (family_id);
CREATE INDEX idx_refresh_tokens_replaced_at ON refresh_tokens USING btree (replaced_at);
ALTER TABLE refresh_tokens ENABLE ROW LEVEL SECURITY;

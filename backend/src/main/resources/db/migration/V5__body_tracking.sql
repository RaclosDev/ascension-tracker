-- Body weight, daily steps and progress photos.

CREATE TABLE weight_entries (
    date date NOT NULL,
    weight double precision NOT NULL,
    created_at timestamp(6) without time zone,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_email character varying(255) NOT NULL,
    CONSTRAINT chk_weight_entries_positive CHECK ((weight > (0)::double precision)),
    CONSTRAINT weight_entries_pkey PRIMARY KEY (id),
    CONSTRAINT weight_entries_user_email_date_key UNIQUE (user_email, date),
    CONSTRAINT fk_weight_entries_user_email FOREIGN KEY (user_email) REFERENCES users(email) ON UPDATE CASCADE
);
CREATE INDEX idx_weight_entries_user_email ON weight_entries USING btree (user_email);
ALTER TABLE weight_entries ENABLE ROW LEVEL SECURITY;

CREATE TABLE steps_entries (
    date date NOT NULL,
    steps integer NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_email character varying(255) NOT NULL,
    CONSTRAINT chk_steps_entries_non_negative CHECK ((steps >= 0)),
    CONSTRAINT steps_entries_pkey PRIMARY KEY (id),
    CONSTRAINT steps_entries_user_email_date_key UNIQUE (user_email, date),
    CONSTRAINT fk_steps_entries_user_email FOREIGN KEY (user_email) REFERENCES users(email) ON UPDATE CASCADE
);
CREATE INDEX idx_steps_entries_user_email ON steps_entries USING btree (user_email);
ALTER TABLE steps_entries ENABLE ROW LEVEL SECURITY;

CREATE TABLE progress_photos (
    id uuid DEFAULT gen_random_uuid() NOT NULL,
    user_id uuid NOT NULL,
    pose character varying(10) NOT NULL,
    taken_on date NOT NULL,
    object_key character varying(200) NOT NULL,
    content_type character varying(20) NOT NULL,
    size_bytes integer NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT ck_progress_photos_pose CHECK (pose IN ('FRONT', 'SIDE', 'BACK')),
    CONSTRAINT ck_progress_photos_size CHECK ((size_bytes > 0)),
    CONSTRAINT progress_photos_pkey PRIMARY KEY (id),
    CONSTRAINT progress_photos_object_key_key UNIQUE (object_key),
    CONSTRAINT progress_photos_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX idx_progress_photos_user ON progress_photos USING btree (user_id, taken_on DESC);
ALTER TABLE progress_photos ENABLE ROW LEVEL SECURITY;

CREATE TABLE photo_object_deletions (
    object_key text NOT NULL,
    attempts integer DEFAULT 0 NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    next_try_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT photo_object_deletions_pkey PRIMARY KEY (object_key)
);
CREATE INDEX idx_photo_object_deletions_due ON photo_object_deletions USING btree (next_try_at);
ALTER TABLE photo_object_deletions ENABLE ROW LEVEL SECURITY;
